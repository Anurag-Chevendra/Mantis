// HTMLOptions configure the HTML report.
type HTMLOptions struct {
	Title   string // project name shown at the top
	FeedURL string // evidence page prefix, e.g. https://trail.snappyfeet.org/?p=
	// Live marks a report written while a scan is still running. The page
	// reloads itself every few seconds; Mantis rewrites the file as results
	// arrive and drops Live on the final write.
	Live *Live
}

// Live is the progress shown on an unfinished report.
type Live struct {
	Phase   string   `json:"phase"`           // one line for the banner
	Done    int      `json:"done"`            // versions answered so far
	Total   int      `json:"total"`           // versions being checked
	Pending []string `json:"pending"`         // name@version not answered yet
	Stopped bool     `json:"stopped"`         // the scan ended early; stop reloading
	Note    string   `json:"note,omitempty"`  // replaces the default progress line
	Refresh int      `json:"-"`               // reload interval in seconds; 0 means 2
	Links   []string `json:"links,omitempty"` // console pages for this run
}

// WriteHTML writes a single self contained HTML file: no external fonts,
// scripts, images or requests. The page's Content Security Policy allows
// only the inline style and script below, pinned by their SHA-256 hashes,
// and blocks every network fetch, so opening a report can never phone
// home. Package names from lockfiles are untrusted and are only ever
// inserted with textContent.
func WriteHTML(w io.Writer, inv *Inventory, opt HTMLOptions) error {
	data, err := json.Marshal(struct {
		Inv   *Inventory `json:"inv"`
		Title string     `json:"title"`
		Feed  string     `json:"feed"`
		Live  *Live      `json:"live,omitempty"`
	}{inv, opt.Title, opt.FeedURL, opt.Live})
	if err != nil {
		return err
	}
	// encoding/json already escapes <, > and &, so the data cannot close
	// the script element it sits in.
	csp := "default-src 'none'; style-src '" + hash(htmlStyle) + "'; script-src '" + hash(htmlScript) +
		"'; img-src data:; base-uri 'none'; form-action 'none'"
	title := opt.Title
	if title == "" {
		title = "project"
	}
	var b bytes.Buffer
	b.WriteString("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
	b.WriteString("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\n")
	b.WriteString("<meta http-equiv=\"Content-Security-Policy\" content=\"" + csp + "\">\n")
	b.WriteString("<meta name=\"referrer\" content=\"no-referrer\">\n")
	if opt.Live != nil && !opt.Live.Stopped {
		every := opt.Live.Refresh
		if every <= 0 {
			every = 2
		}
		fmt.Fprintf(&b, "<meta http-equiv=\"refresh\" content=\"%d\">\n", every)
	}
	b.WriteString("<title>Mantis · " + htmlEscape(title) + "</title>\n")
	b.WriteString("<style>" + htmlStyle + "</style>\n</head>\n<body>\n")
	b.WriteString(htmlBody)
	b.WriteString("<script type=\"application/json\" id=\"data\">")
	b.Write(data)
	b.WriteString("</script>\n<script>" + htmlScript + "</script>\n</body>\n</html>\n")
	_, err = w.Write(b.Bytes())
	return err
}

func hash(s string) string {
	h := sha256.Sum256([]byte(s))
	return "sha256-" + base64.StdEncoding.EncodeToString(h[:])
}

func htmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&#39;").Replace(s)
}

